#!/usr/bin/env python3
"""Compare project.yml's Swift package pins with their upstream releases.

    python3 scripts/package_pins.py            # print the table
    python3 scripts/package_pins.py --issue    # and keep one issue in step with it

Dependabot cannot watch these packages: the project is generated by XcodeGen, so there is
no Package.swift for it to read. This reads the `packages:` block of project.yml, asks
GitHub for each package's newest release (or, for a repository that publishes none, its
highest version tag), and lists every pin that is behind.

With `--issue` it keeps ONE open issue, titled ISSUE_TITLE, listing the updates: it opens
the issue when there are updates and none is open, rewrites its body when one is open, and
closes it when every pin is current. Nothing is bumped here; a bump is a reviewed pull
request, because some pins move together (district-ios and district-macos name the same
DistrictCore and WebRTC, and a test package's dependencies are pinned to the versions its
own Package.resolved records).

Needs `gh`, authenticated (GH_TOKEN in CI), and the network.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ISSUE_TITLE = "Swift package updates available"

# A release version: digits separated by dots, with an optional leading "v". Anything with a
# suffix (-beta.1, -rc2, -alpha) is a pre-release and never counts as newer.
VERSION = re.compile(r"v?(\d+(?:\.\d+)*)")


@dataclass(frozen=True)
class Pin:
    name: str
    owner: str
    repo: str
    version: str


def parse_pins(spec: str) -> list[Pin]:
    """Every package under `packages:` that names a GitHub URL and an exactVersion.

    A package pinned another way (`from:`, `branch:`, `revision:`) is left out: there is no
    single version to compare.
    """
    pins: list[Pin] = []
    in_packages = False
    name = url = None
    for line in spec.splitlines():
        if re.match(r"^\S", line):
            in_packages = line.rstrip() == "packages:"
            name = url = None
            continue
        if not in_packages:
            continue
        if m := re.match(r"^  ([A-Za-z0-9_.-]+):\s*$", line):
            name, url = m.group(1), None
        elif m := re.match(r"^    url:\s*\"?(\S+?)\"?\s*$", line):
            url = m.group(1)
        elif (m := re.match(r"^    exactVersion:\s*\"?([^\s\"]+)\"?\s*$", line)) and name and url:
            gh = re.fullmatch(r"https://github\.com/([^/]+)/(.+?)(?:\.git)?/?", url)
            if gh:
                pins.append(Pin(name, gh.group(1), gh.group(2), m.group(1)))
    return pins


def version_key(text: str) -> tuple[int, ...] | None:
    """The numeric parts of a release version, or None for a pre-release or a non-version."""
    m = VERSION.fullmatch(text.strip())
    if not m:
        return None
    return tuple(int(part) for part in m.group(1).split("."))


def newer(latest: str, pinned: str) -> bool:
    """Whether `latest` is a higher release than `pinned`, comparing 1.2 as 1.2.0."""
    a, b = version_key(latest), version_key(pinned)
    if a is None or b is None:
        return False
    width = max(len(a), len(b))
    return a + (0,) * (width - len(a)) > b + (0,) * (width - len(b))


def highest(tags: list[str]) -> str | None:
    """The highest release version among `tags`, pre-releases left out."""
    best: tuple[tuple[int, ...], str] | None = None
    for tag in tags:
        key = version_key(tag)
        if key is not None and (best is None or key > best[0]):
            best = (key, tag)
    return best[1] if best else None


def gh_json(*args: str) -> object | None:
    result = subprocess.run(["gh", "api", *args], capture_output=True, text=True, check=False)
    if result.returncode != 0:
        return None
    return json.loads(result.stdout)


def latest_release(pin: Pin) -> str | None:
    """The repository's latest release tag, or its highest version tag when it has no release."""
    release = gh_json(f"repos/{pin.owner}/{pin.repo}/releases/latest")
    if isinstance(release, dict) and release.get("tag_name"):
        tag = str(release["tag_name"])
        if version_key(tag) is not None:
            return tag
    tags = gh_json(f"repos/{pin.owner}/{pin.repo}/tags?per_page=100")
    if isinstance(tags, list):
        return highest([str(t.get("name", "")) for t in tags])
    return None


def table(rows: list[tuple[Pin, str]]) -> str:
    lines = ["| Package | Pinned | Latest | Releases |", "|---|---|---|---|"]
    for pin, latest in rows:
        url = f"https://github.com/{pin.owner}/{pin.repo}/releases"
        lines.append(f"| {pin.name} | {pin.version} | {latest} | {url} |")
    return "\n".join(lines)


def issue_body(rows: list[tuple[Pin, str]], unknown: list[Pin]) -> str:
    parts = [
        "The weekly package pin check (`.github/workflows/package-pins.yml`) found these "
        "`project.yml` pins behind their newest upstream release:",
        "",
        table(rows),
        "",
        "Each bump is its own reviewed pull request. Some pins move together: DistrictCore and "
        "WebRTC match district-ios and district-macos, and a test package's dependencies "
        "follow the versions its own Package.resolved records. This issue is rewritten each "
        "week and closed when every pin is current.",
    ]
    if unknown:
        names = ", ".join(p.name for p in unknown)
        parts += ["", f"No release or version tag could be read for: {names}."]
    return "\n".join(parts)


def sync_issue(body: str | None) -> None:
    """Open, rewrite or close the one issue titled ISSUE_TITLE."""
    found = subprocess.run(
        ["gh", "issue", "list", "--state", "open", "--search", f'in:title "{ISSUE_TITLE}"',
         "--json", "number,title", "--limit", "20"],
        capture_output=True, text=True, check=True,
    )
    numbers = [i["number"] for i in json.loads(found.stdout) if i["title"] == ISSUE_TITLE]
    if body is None:
        for number in numbers:
            subprocess.run(["gh", "issue", "close", str(number), "--comment",
                            "Every project.yml pin is at its newest upstream release."], check=True)
            print(f"closed #{number}: every pin is current")
        return
    if numbers:
        subprocess.run(["gh", "issue", "edit", str(numbers[0]), "--body", body], check=True)
        print(f"updated #{numbers[0]}")
    else:
        subprocess.run(["gh", "issue", "create", "--title", ISSUE_TITLE, "--body", body], check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--issue", action="store_true", help="keep the one updates issue in step")
    parser.add_argument("--spec", default=str(ROOT / "project.yml"))
    args = parser.parse_args()
    pins = parse_pins(Path(args.spec).read_text())
    if not pins:
        print(f"FATAL - no exactVersion pins found in {args.spec}")
        return 1
    rows: list[tuple[Pin, str]] = []
    unknown: list[Pin] = []
    for pin in pins:
        latest = latest_release(pin)
        if latest is None:
            unknown.append(pin)
            print(f"{pin.name}: pinned {pin.version}, no release or version tag readable")
        elif newer(latest, pin.version):
            rows.append((pin, latest))
            print(f"{pin.name}: pinned {pin.version}, latest {latest}")
        else:
            print(f"{pin.name}: pinned {pin.version}, current")
    if args.issue:
        sync_issue(issue_body(rows, unknown) if rows else None)
    return 0


if __name__ == "__main__":
    sys.exit(main())
