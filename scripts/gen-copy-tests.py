#!/usr/bin/env python3
"""Writes the test that every generated Copy accessor says what its catalog entry says, or
checks that the committed test is current.

    python3 scripts/gen-copy-tests.py           # rewrite App/Tests/Generated/CopyCatalogTests.swift
    python3 scripts/gen-copy-tests.py --check   # fail when the committed file is stale (CI)

`scripts/gen-l10n.py` turns `l10n/macos.toml` into `App/Sources/L10n/Generated/Copy.swift`,
and its `--check` proves the Swift is what the generator writes. This proves the other half
at run time: that each accessor, called in the app, answers the catalog's English under
English and the catalog's French under Canadian French (through `L10nRuntime`, the switch
the app flips), with arguments put where the catalog's placeholders are and the plural form
the catalog gives for one and for several.

⚠️ ACCESSORS WHOSE ARGUMENTS ARE FORMATTED (`date`, `duration`, `money`, `time`) ARE LEFT
OUT: their text depends on the core's formatters, which their own tests pin. Every
accessor with no argument, or with only `str` and `int` ones, is here.
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "l10n" / "macos.toml"
OUTPUT = ROOT / "App" / "Tests" / "Generated" / "CopyCatalogTests.swift"
SAMPLE_INT = {"one": 1, "other": 5}


def swift_literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return f'"{escaped}"'


def fill(template: str, values: dict[str, str]) -> str:
    def replace(match: re.Match[str]) -> str:
        name = match.group(1)
        if name not in values:
            raise SystemExit(f"placeholder {{{name}}} has no argument in {template!r}")
        return values[name]

    return re.sub(r"\{([A-Za-z_][A-Za-z0-9_]*)\}", replace, template)


def calls(entry: dict) -> list[tuple[str, str, str]] | None:
    """(call, english, french) for each assertion, or None when the entry is left out."""
    swift = entry.get("id", {}).get("swift")
    if not swift:
        return None
    args = entry.get("args") or {}
    if any(kind not in ("str", "int") for kind in args.values()):
        return None
    # A `fixed` entry (a product name, text for staff) is the same in both languages.
    en = entry["en"]
    fr = entry["en"] if entry.get("fixed") else entry["fr"]
    if "(" not in swift:
        if isinstance(en, dict):
            raise SystemExit(f"{swift}: a plural with no argument")
        return [(swift, en, fr)]
    name, labels = re.fullmatch(r"([\w.]+)\(((?:\w+:)*)\)", swift).groups()
    labels = labels.split(":")[:-1]
    if len(labels) != len(args):
        raise SystemExit(f"{swift}: {len(labels)} labels for {len(args)} arguments")
    plural = isinstance(en, dict)
    forms = ["one", "other"] if plural else ["other"]
    out = []
    for form in forms:
        values: dict[str, str] = {}
        literals = []
        for label, (arg, kind) in zip(labels, args.items()):
            if kind == "int":
                value = str(SAMPLE_INT[form])
                literal = value
            else:
                value = f"<{arg}>"
                literal = swift_literal(value)
            values[arg] = value
            literals.append(literal if label == "_" else f"{label}: {literal}")
        en_text = en[form] if plural else en
        fr_text = fr[form] if plural else fr
        out.append((f"{name}({', '.join(literals)})", fill(en_text, values), fill(fr_text, values)))
    return out


def render() -> str:
    catalog = tomllib.loads(CATALOG.read_text(encoding="utf-8"))
    lines = [
        "// @generated by scripts/gen-copy-tests.py from l10n/macos.toml. Do not edit; run the script.",
        "// swiftlint:disable all",
        "",
        "import DistrictL10n",
        "@testable import DistrictMac",
        "import XCTest",
        "",
        "/// Every Copy accessor answers its catalog entry's English and French (see the script).",
        "final class CopyCatalogTests: XCTestCase {",
    ]
    counted = 0
    for group, entries in catalog.items():
        if group == "meta":
            continue
        asserts = []
        for key, entry in entries.items():
            for call, en, fr in calls(entry) or []:
                asserts.append((f"{group}.{key}", call, en, fr))
        if not asserts:
            continue
        method = "test_" + re.sub(r"\W", "_", group)
        lines.append(f"    func {method}() {{")
        for key, call, en, _ in asserts:
            lines.append(f"        XCTAssertEqual({call}, {swift_literal(en)}, {swift_literal(key)})")
        lines.append("        L10nRuntime.withLocale(.frCA) {")
        for key, call, _, fr in asserts:
            lines.append(f"            XCTAssertEqual({call}, {swift_literal(fr)}, {swift_literal(key)})")
        lines.append("        }")
        lines.append("    }")
        lines.append("")
        counted += len(asserts)
    if lines[-1] == "":
        lines.pop()
    lines.append("}")
    lines.append("")
    if counted < 1000:
        raise SystemExit(f"only {counted} accessors found; the catalog reader is broken")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"FATAL - {OUTPUT.relative_to(ROOT)} is stale; run python3 scripts/gen-copy-tests.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
